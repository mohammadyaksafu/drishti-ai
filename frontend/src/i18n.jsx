const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
const toBnDigits = (value) => String(value).replace(/[0-9]/g, (d) => BN_DIGITS[d]);

const LangContext = createContext(null);

function initialLang() {
  try {
    const saved = localStorage.getItem('drishti-lang');
    if (saved === 'en' || saved === 'bn') return saved;
  } catch {
    /* storage blocked: fall through */
  }
  return 'bn';
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dataset.lang = lang;
    try {
      localStorage.setItem('drishti-lang', lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const t = useCallback(
    (key, vars) => {
      let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
      if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replace(`{${k}}`, v)));
      return s;
    },
    [lang]
  );

  const num = useCallback((value) => (lang === 'bn' ? toBnDigits(value) : String(value)), [lang]);

  const hazard = useCallback(
    (type, fallback) => {
      const entry = HAZARDS[lang]?.[type];
      return entry ? { name: entry[0], description: entry[1] } : fallback;
    },
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang: setLangState, toggle: () => setLangState((l) => (l === 'bn' ? 'en' : 'bn')), t, num, hazard }),
    [lang, t, num, hazard]
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
